// Font families per language for Indic scripts
const LANGUAGE_FONTS: Record<Language, string> = {
  en: "'Inter', 'Inter Tight', sans-serif",
  ar: "'Noto Sans Arabic', 'Inter', sans-serif",
  te: "'Noto Sans Telugu', 'Inter', sans-serif",
  hi: "'Noto Sans Devanagari', 'Inter', sans-serif",
  kn: "'Noto Sans Kannada', 'Inter', sans-serif",
  ta: "'Noto Sans Tamil', 'Inter', sans-serif",
  ml: "'Noto Sans Malayalam', 'Inter', sans-serif",
  mr: "'Noto Sans Devanagari', 'Inter', sans-serif",
};

const LANGUAGE_LABELS: Record<Language, string> = {
  en: "EN",
  ar: "عر",
  te: "తె",
  hi: "हि",
  kn: "ಕ",
  ta: "த",
  ml: "മ",
  mr: "म",
};

export { LANGUAGE_LABELS };

const VALID_LANGUAGES: Language[] = ["en", "ar", "te", "hi", "kn", "ta", "ml", "mr"];

const defaultValue: I18nContextType = {
  language: "en",
  direction: "ltr",
  setLanguage: () => { },
  t: (key: string, fallback?: string) => fallback || key,
};

const I18nContext = createContext<I18nContextType>(defaultValue);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    if (typeof window === "undefined") return "en";
    try {
      const saved = localStorage.getItem("bos-lang") as Language;
      return VALID_LANGUAGES.includes(saved) ? saved : "en";
    } catch {
      return "en";
    }
  });

  const direction: Direction = language === "ar" ? "rtl" : "ltr";

  useEffect(() => {
    if (typeof window === "undefined") return;
    try {
      document.documentElement.dir = direction;
      document.documentElement.lang = language;
      localStorage.setItem("bos-lang", language);

      // RTL class
      if (language === "ar") {
        document.documentElement.classList.add("rtl");
      } else {
        document.documentElement.classList.remove("rtl");
      }

      // Apply font family for Indic scripts
      document.documentElement.style.setProperty(
        "--font-sans",
        LANGUAGE_FONTS[language]
      );

      // Inject Google Fonts link for Indic scripts dynamically
      const fontLinks: Record<string, string> = {
        te: "https://fonts.googleapis.com/css2?family=Noto+Sans+Telugu:wght@300..900&display=swap",
        hi: "https://fonts.googleapis.com/css2?family=Noto+Sans+Devanagari:wght@300..900&display=swap",
        kn: "https://fonts.googleapis.com/css2?family=Noto+Sans+Kannada:wght@300..900&display=swap",
        ar: "https://fonts.googleapis.com/css2?family=Noto+Sans+Arabic:wght@300..900&display=swap",
        ta: "https://fonts.googleapis.com/css2?family=Noto+Sans+Tamil:wght@300..900&display=swap",
        ml: "https://fonts.googleapis.com/css2?family=Noto+Sans+Malayalam:wght@300..900&display=swap",
        mr: "https://fonts.googleapis.com/css2?family=Noto+Sans+Devanagari:wght@300..900&display=swap",
      };

      if (fontLinks[language]) {
        const linkId = `bos-font-${language}`;
        if (!document.getElementById(linkId)) {
          const link = document.createElement("link");
          link.id = linkId;
          link.rel = "stylesheet";
          link.href = fontLinks[language];
          document.head.appendChild(link);
        }
      }
    } catch (e) {
      console.error("Failed to update document direction:", e);
    }
  }, [language, direction]);

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
  };

  const t = (key: string, fallback?: string): string => {
    if (!key) return fallback || "";
    // Direct match
    if (translations[language]?.[key]) return translations[language][key];
    // Trimmed match
    const trimmedKey = key.trim();
    if (translations[language]?.[trimmedKey]) return translations[language][trimmedKey];
    // Fallback provided
    if (fallback) return fallback;
    // Default English dictionary match
    if (translations.en?.[key]) return translations.en[key];
    if (translations.en?.[trimmedKey]) return translations.en[trimmedKey];
    return key;
  };

  return (
    <I18nContext.Provider value={{ language, direction, setLanguage, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
